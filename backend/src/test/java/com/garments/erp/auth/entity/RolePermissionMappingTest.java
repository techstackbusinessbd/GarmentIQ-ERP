package com.garments.erp.auth.entity;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

/**
 * =============================================================================
 * [EN] Unit Test Suite for Role and Permission Entity Mappings
 * [BN] রোল এবং পারমিশন এন্টিটি ম্যাপিংয়ের ইউনিট টেস্ট স্যুট
 * =============================================================================
 * [EN] Tests entity lifecycle hooks, UUIDv7 generation, permission collection
 *      associations, and role equality within multi-tenant boundaries.
 * [BN] এন্টিটি লাইফসাইকেল হুক, UUIDv7 জেনারেশন, পারমিশন কালেকশন অ্যাসোসিয়েশন
 *      এবং টেন্যান্ট বাউন্ডারির মধ্যে রোলের সমতা যাচাই করে।
 */
class RolePermissionMappingTest {

    /**
     * [EN] Tests adding and removing granular permissions to a role entity
     * [BN] রোলে পারমিশন যুক্ত করা এবং অপসারণ করা যাচাই
     */
    @Test
    @DisplayName("Should successfully associate and dissociate permissions with Role")
    void testAssociateAndDissociatePermissions() {
        UUID tenantId = UUID.randomUUID();
        Role role = new Role(tenantId, "ROLE_MERCHANDISER", "Garments Merchandiser");

        Permission perm1 = new Permission("ORDER:READ", "MERCHANDISING", "View buyer orders");
        Permission perm2 = new Permission("ORDER:CREATE", "MERCHANDISING", "Create buyer orders");

        role.addPermission(perm1);
        role.addPermission(perm2);

        assertEquals(2, role.getPermissions().size(), "Role should hold exactly 2 permissions");
        assertTrue(role.getPermissions().contains(perm1), "Role must contain ORDER:READ");
        assertTrue(role.getPermissions().contains(perm2), "Role must contain ORDER:CREATE");

        role.removePermission(perm1);
        assertEquals(1, role.getPermissions().size(), "Role should hold exactly 1 permission after removal");
        assertFalse(role.getPermissions().contains(perm1), "Role must no longer contain ORDER:READ");
    }

    /**
     * [EN] Tests JPA @PrePersist hooks for UUIDv7 generation and timestamp initialization
     * [BN] JPA @PrePersist হুকে UUIDv7 আইডি এবং টাইমস্ট্যাম্প স্বয়ংক্রিয় সেট হওয়া যাচাই
     */
    @Test
    @DisplayName("Should generate valid UUIDv7 on entity pre-persist lifecycle")
    void testPrePersistGeneratesUuidV7() {
        UUID tenantId = UUID.randomUUID();
        Role role = new Role(tenantId, "ROLE_CUTTING_MANAGER", "Cutting Room Manager");
        Permission permission = new Permission("CUTTING:EXECUTE", "CUTTING", "Execute cutting markers");

        assertNull(role.getId(), "Role ID must be null before persist hook");
        assertNull(permission.getId(), "Permission ID must be null before persist hook");

        role.onCreate();
        permission.onCreate();

        assertNotNull(role.getId(), "Role ID must be generated by pre-persist");
        assertEquals(7, role.getId().version(), "Role ID must be UUIDv7");
        assertNotNull(role.getCreatedAt(), "Role createdAt must be initialized");

        assertNotNull(permission.getId(), "Permission ID must be generated by pre-persist");
        assertEquals(7, permission.getId().version(), "Permission ID must be UUIDv7");
        assertNotNull(permission.getCreatedAt(), "Permission createdAt must be initialized");
    }

    /**
     * [EN] Tests multi-tenant role equality based on tenantId and roleCode
     * [BN] tenantId এবং roleCode-এর ভিত্তিতে রোলের নির্ভুল সমতা যাচাই
     */
    @Test
    @DisplayName("Should correctly evaluate role equality by tenantId and roleCode")
    void testRoleEquality() {
        UUID tenantA = UUID.randomUUID();
        UUID tenantB = UUID.randomUUID();

        Role role1 = new Role(tenantA, "ROLE_ADMIN", "Admin Tenant A");
        Role role2 = new Role(tenantA, "ROLE_ADMIN", "Admin Tenant A Dup");
        Role role3 = new Role(tenantB, "ROLE_ADMIN", "Admin Tenant B");

        assertEquals(role1, role2, "Roles with same tenantId and roleCode must be equal");
        assertEquals(role1.hashCode(), role2.hashCode(), "HashCodes must match for equal roles");
        assertNotEquals(role1, role3, "Roles across different tenants must NOT be equal");
    }
}
